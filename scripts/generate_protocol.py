"""Generate declaration types from the maintained JSON Schema, without SDK dependencies."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'devmesh-protocol'

def literal(value): return json.dumps(value,ensure_ascii=False,separators=(',',':'))
def ts(schema):
    if '$ref' in schema: return schema['$ref'].split('/')[-1]
    if 'const' in schema: return literal(schema['const'])
    if 'enum' in schema: return ' | '.join(literal(x) for x in schema['enum'])
    if any(key in schema for key in ('oneOf','anyOf','allOf')):
        base={key:value for key,value in schema.items() if key not in ('oneOf','anyOf','allOf')}
        parts=[ts(base)] if ('properties' in base or 'type' in base) else []
        for key in ('oneOf','anyOf'):
            if key in schema:parts.append('('+' | '.join(ts(value) for value in schema[key])+')')
        parts.extend(ts(value) for value in schema.get('allOf',[]))
        return '('+' & '.join(parts or ['unknown'])+')'
    kind=schema.get('type')
    if isinstance(kind,list): return '('+' | '.join(ts(dict(schema,type=k)) for k in kind)+')'
    if kind=='array': return f'Array<{ts(schema.get("items",{}))}>'
    if kind=='object' or 'properties' in schema:
        props=schema.get('properties',{})
        fields=[f'{literal(k)}'+('' if k in schema.get('required',[]) else '?')+': '+ts(v) for k,v in props.items()]
        if schema.get('additionalProperties',True) is not False:
            fields.append('[key: string]: unknown')
        return '{ '+'; '.join(fields)+' }'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')

for path in (BASE/'schemas').glob('*.json'):
    schema=json.loads(path.read_text());name=path.name.split('.')[0]
    declarations=['// Generated by scripts/generate_protocol.py. Edit schemas, then regenerate.']
    declarations += ['export type '+key+' = '+ts(value)+';' for key,value in schema.get('$defs',{}).items()]
    declarations += ['export type '+name.title()+' = '+ts(schema)+';']
    dest=BASE/'ts'/f'{name}.ts';dest.parent.mkdir(exist_ok=True);dest.write_text('\n'.join(declarations)+'\n')
